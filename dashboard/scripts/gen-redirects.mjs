// Generates public/_redirects at build time so the Firebase auth proxy points at the correct
// per-brand Firebase project. `_redirects` is a static file and can't read env, so we template
// it here — keyed by VITE_BRAND, so the build only needs that one variable.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const AUTH_PROXY = {
	waveassist: "https://waveassistdashboard.firebaseapp.com",
	gitzoid: "https://gitzoid-dashboard.firebaseapp.com",
};

const brand = (process.env.VITE_BRAND || "waveassist").toLowerCase();
const authProxy = AUTH_PROXY[brand] || AUTH_PROXY.waveassist;

const contents = `# GENERATED by scripts/gen-redirects.mjs — do not edit by hand.
# Firebase auth handler proxy (per-brand). SPA fallback below.
/__/auth/*  ${authProxy}/__/auth/:splat  200!
/* /index.html 200
`;

const out = fileURLToPath(new URL("../public/_redirects", import.meta.url));
writeFileSync(out, contents);
console.log(`[gen-redirects] brand=${brand} auth proxy -> ${authProxy}`);
